async page => {
  const failures = [];
  const consoleErrors = [];
  const requests = [];
  page.on('pageerror', error => failures.push(error.message));
  page.on('console', msg => { if (msg.type() === 'error') consoleErrors.push(msg.text()); });
  page.on('request', req => requests.push(req.url()));
  const assert = (value, message) => { if (!value) throw new Error(message); };
  await page.setViewportSize({width:1100,height:780});
  await page.reload();
  await page.getByRole('button', {name:'地理叠加',exact:true}).click();
  await page.getByRole('heading', {name:'地理叠加 · 后期图层'}).waitFor();
  assert(await page.getByText('当前运行于浏览器。', {exact:false}).isVisible(), 'Browser mode must state native bridge requirement');
  assert(!await page.getByRole('heading', {name:/正在初始化 Python/}).isVisible(), 'Python startup overlay must not block geo');
  const geo = page.getByTestId('geographic-overlay-page');
  const enabled = page.getByRole('checkbox', {name:/启用地图叠加/});
  assert(!await enabled.isChecked(), 'Overlay defaults to disabled');
  assert(await page.getByRole('button', {name:'保存项目…',exact:true}).isDisabled(), 'No photo cannot save');
  const range = await geo.locator('aside input[type=range]').evaluateAll(nodes => nodes.map(n=>({min:n.min,max:n.max,step:n.step,value:n.value,label:n.closest('label').innerText})));
  assert(range.find(n=>n.label.includes('覆盖半径')).value === '3', 'radius default is exact 3');
  assert(range.find(n=>n.label.includes('边缘羽化')).max === '0.3', 'feather max matches native');
  const before = await geo.locator('aside details').first().boundingBox();
  await geo.locator('aside details summary').all().then(async nodes => {for (const n of nodes) if (await n.evaluate(e=>e.parentElement.open)) await n.click();});
  const after = await geo.locator('aside details').first().boundingBox();
  assert(Math.abs(before.x-after.x)<=1 && Math.abs(before.width-after.width)<=1, 'Sidebar width must stay stable after collapse');
  await page.getByText('位置', {exact:true}).click();
  await page.getByRole('spinbutton',{name:'纬度',exact:true}).fill('0');
  await page.getByRole('spinbutton',{name:'纬度',exact:true}).press('Tab');
  assert(await page.getByRole('checkbox',{name:'使用位置坐标',exact:true}).isChecked(), 'manual zero latitude is valid location');
  await page.getByText('地图来源与样式', {exact:true}).click();
  await page.getByRole('combobox',{name:'数据来源',exact:true}).selectOption('1');
  assert(!await geo.getByRole('alert').isVisible(), 'OSM is available rather than blocked as unsupported');
  assert(await geo.getByRole('combobox',{name:'数据来源',exact:true}).inputValue() === '1', 'real OSM selection is active');
  await page.getByRole('combobox',{name:'数据来源',exact:true}).selectOption('0');
  await page.getByRole('combobox',{name:'叠加风格',exact:true}).selectOption('3');
  assert(await page.getByText('Terrain 地形图层尚未实现。请选择自动、城市或海岸样式。',{exact:true}).isVisible(), 'Terrain unsupported is explicit');
  await page.getByRole('combobox',{name:'叠加风格',exact:true}).selectOption('0');
  assert(!requests.some(url=>url.includes('overpass-api')), 'Browser mode must not issue map requests without a selected native photo');
  assert(failures.length===0, 'No page errors: '+failures.join(';'));
  assert(consoleErrors.length===0, 'No console errors: '+consoleErrors.join(';'));
  return {status:'passed',url:page.url(),viewport:[1100,780],checks:12,sidebar_before:before,sidebar_after:after,console_errors:consoleErrors,page_errors:failures,network_requests:requests.length};
}
